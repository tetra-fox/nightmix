CREATE TABLE public.artists (
	id int8 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"name" text NOT NULL,
	username text NOT NULL,
	CONSTRAINT artists_pkey PRIMARY KEY (id),
	CONSTRAINT artists_username_key UNIQUE (username)
);

CREATE TABLE public.mixes (
	id int8 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	created_at timestamptz NOT NULL DEFAULT now(),
	artist_id int8 NOT NULL,
	title text NOT NULL,
	description text NOT NULL DEFAULT ''::text,
	tags _text NOT NULL DEFAULT '{}'::text[],
	audio_url text NOT NULL,
	artwork_url text NOT NULL,
	slug text NOT NULL,
	CONSTRAINT mixes_pkey PRIMARY KEY (id),
	CONSTRAINT unique_slugs_per_artist UNIQUE (artist_id, slug),
	CONSTRAINT mixes_artist_id_fkey FOREIGN KEY (artist_id) REFERENCES public.artists(id)
);

CREATE TABLE public.timestamps (
	id int8 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	mix_id int8 NOT NULL,
	timestamp_ms int8 NOT NULL,
	"timestamp" text NOT NULL,
	artist text NOT NULL,
	title text NOT NULL,
	CONSTRAINT timestamps_pkey PRIMARY KEY (id),
	CONSTRAINT timestamps_mix_id_fkey FOREIGN KEY (mix_id) REFERENCES public.mixes(id) ON DELETE CASCADE
);
CREATE INDEX timestamps_mix_id_idx ON public.timestamps USING btree (mix_id);